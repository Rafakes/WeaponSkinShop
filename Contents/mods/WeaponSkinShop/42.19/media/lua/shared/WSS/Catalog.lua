function WSS.getSkin(fullType, id)
    local entry = WSS.catalog[fullType]
    if not entry then return nil end
    for _, skin in ipairs(entry.skins) do
        if skin.id == id then return skin end
    end
end

function WSS.isGun(item)
    return item and instanceof(item, "HandWeapon") and item:isRanged()
end

-- Bounded traversal of the player's inventory, including bags. Never search the floor.
function WSS.findItem(container, id)
    local queue, head, visited, count = { container }, 1, {}, 0
    while head <= #queue do
        local current = queue[head]
        head = head + 1
        if current and not visited[current] then
            visited[current] = true
            local items = current:getItems()
            for i = 0, items:size() - 1 do
                count = count + 1
                if count > 4096 then return nil end
                local item = items:get(i)
                if item:getID() == id then return item end
                if instanceof(item, "InventoryContainer") then
                    queue[#queue + 1] = item:getInventory()
                end
            end
        end
    end
end

-- Shared visual projection only; currency and unlocks live exclusively on the server.
function WSS.applyVisual(item, id)
    local entry = WSS.catalog[item:getFullType()]
    if not entry then return false end
    local skin = WSS.getSkin(item:getFullType(), id)
    if id ~= "original" and not skin then return false end
    local model = skin and skin.model or entry.originalModel
    item:setWeaponSprite(model)
    if skin then
        item:setWorldStaticModel(skin.model)
    else
        -- Clearing the override restores the script default, without passing nil to
        -- the overloaded Java setWorldStaticModel(String/ModelKey) method.
        item:getModData().worldStaticModel = nil
    end
    return true
end

return WSS
